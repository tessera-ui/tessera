use super::{app_assets, application::Application, build};

static TEMPLATE: Dir = include_dir!("$CARGO_MANIFEST_DIR/platforms/apple");
const PROJECT_DIR: &str = "gen/apple";

#[derive(Args)]
pub struct InitOptions {
    /// Package to build or run
    #[arg(short, long)]
    package: Option<String>,
    /// Executable to build
    #[arg(long)]
    bin: Option<String>,
    /// Regenerate the editable project files, replacing local changes
    #[arg(long)]
    force: bool,
}

#[derive(Args)]
pub struct IosBuildOptions {
    /// Build with the release profile
    #[arg(short, long)]
    release: bool,
    /// Build a device IPA instead of a simulator application
    #[arg(long)]
    device: bool,
    /// Package to build or run
    #[arg(short, long)]
    package: Option<String>,
    /// Executable to build
    #[arg(long)]
    bin: Option<String>,
    /// Write profiler records to this path inside the application container
    #[arg(long, value_name = "PATH")]
    profiling_output: Option<PathBuf>,
}

pub(super) fn deployment_target() -> String {
    env::var("IPHONEOS_DEPLOYMENT_TARGET").unwrap_or_else(|_| "15.0".into())
}

fn run(command: &mut Command) -> Result<()> {
    ensure!(
        command
            .status()
            .with_context(|| format!("Failed to run {command:?}"))?
            .success(),
        "Command failed: {command:?}"
    );
    Ok(())
}

fn project_dir(app: &Application) -> Result<PathBuf> {
    Ok(app
        .package
        .manifest_path
        .parent()
        .context("Missing package directory")?
        .as_std_path()
        .join(PROJECT_DIR))
}

/// Generates the Xcode project, or regenerates its editable files with `force`.
pub fn init(options: InitOptions) -> Result<()> {
    ensure!(
        cfg!(target_os = "macos"),
        "Generating the Xcode project requires macOS"
    );
    let app = Application::new(options.package.as_deref(), options.bin.as_deref())?;
    let directory = project_dir(&app)?;
    let project = directory.join(format!("{}.xcodeproj", app.binary));
    let exists = project.exists();
    if exists && !options.force {
        output::warn(format!(
            "Xcode project already exists at {}; pass --force to regenerate its editable files",
            directory.display()
        ));
    }
    if !exists || options.force {
        let mut handlebars = Handlebars::new();
        handlebars.register_escape_fn(handlebars::no_escape);
        write_template_dir(
            &TEMPLATE,
            &directory,
            &handlebars,
            &json!({ "project": app.binary, "bin": app.binary }),
        )?;
    }
    sync_project(&app)?;
    if !exists || options.force {
        run(Command::new("xcodegen")
            .args(["generate", "--spec", "project.yml"])
            .current_dir(&directory))
        .context("Install XcodeGen with `brew install xcodegen`")?;
        output::status(
            "Generated",
            format!("Xcode project at {}", project.display()),
        );
    }
    Ok(())
}

/// Regenerates the files cargo-tessera maintains inside the Xcode project.
fn sync_project(app: &Application) -> Result<()> {
    let directory = project_dir(app)?;
    ensure!(
        directory.join("project.yml").is_file(),
        "Xcode project not initialized. Run `cargo tessera apple init` first."
    );
    let version = &app.package.version;
    let mut settings = String::from(
        "// @generated by cargo-tessera from tessera.toml and Cargo.toml; do not edit.\n",
    );
    for (key, value) in [
        ("PRODUCT_BUNDLE_IDENTIFIER", app.identity.identifier.clone()),
        ("TESSERA_DISPLAY_NAME", app.identity.name.clone()),
        ("MARKETING_VERSION", version.to_string()),
        (
            "CURRENT_PROJECT_VERSION",
            format!("{}.{}.{}", version.major, version.minor, version.patch),
        ),
        ("TESSERA_PACKAGE", app.package.name.to_string()),
        ("TESSERA_BIN", app.binary.clone()),
    ] {
        settings.push_str(&format!("{key} = {value}\n"));
    }
    write_if_changed(&directory.join("tessera.xcconfig"), settings.as_bytes())?;
    app_assets::apple(&app.identity, &directory.join("Tessera.xcassets"))?;
    Ok(())
}

/// Builds the Rust executable for the Xcode target being built.
///
/// Reads the build settings Xcode exports to run script phases.
pub fn rust_build() -> Result<()> {
    let setting = |name: &str| {
        env::var(name).map_err(|_| {
            anyhow!("{name} is not set; this command runs from an Xcode build phase")
        })
    };
    let platform = setting("PLATFORM_NAME")?;
    let configuration = setting("CONFIGURATION")?;
    let package = setting("TESSERA_PACKAGE")?;
    let binary = setting("TESSERA_BIN")?;
    let bundle = PathBuf::from(setting("TARGET_BUILD_DIR")?);
    let executable = bundle.join(setting("EXECUTABLE_PATH")?);
    let resources = bundle.join(setting("UNLOCALIZED_RESOURCES_FOLDER_PATH")?);
    let profiling_output = env::var_os("TESSERA_PROFILING_OUTPUT").map(PathBuf::from);
    let triples = setting("ARCHS")?
        .split_whitespace()
        .map(|arch| triple(&platform, arch))
        .collect::<Result<Vec<_>>>()?;
    // Xcode exports the SDK of the Apple target, which would break linking
    // build scripts for the host; rustc locates each target's SDK itself.
    // SAFETY: no other threads have been started yet.
    unsafe { env::remove_var("SDKROOT") };

    let mut executables = Vec::new();
    for triple in &triples {
        let built = build::execute(
            configuration == "Release",
            Some(triple),
            Some(&package),
            Some(&binary),
            profiling_output.as_deref(),
            false,
            Some(AssetBackend::Platform),
        )?
        .into_iter()
        .find(|path| path.file_stem().is_some_and(|stem| stem == binary.as_str()))
        .context("Cargo did not produce the selected executable")?;
        executables.push(built);
    }
    fs::create_dir_all(executable.parent().context("Missing executable directory")?)?;
    if let [single] = executables.as_slice() {
        fs::copy(single, &executable)?;
    } else {
        run(Command::new("lipo")
            .arg("-create")
            .args(&executables)
            .arg("-output")
            .arg(&executable))?;
    }
    let assets = executables[0].with_extension("resources");
    if assets.is_dir() {
        for file in asset_files(&assets)? {
            let target = resources.join(file.strip_prefix(&assets)?);
            fs::create_dir_all(target.parent().context("Missing resource directory")?)?;
            fs::copy(&file, target)?;
        }
    }
    Ok(())
}

fn triple(platform: &str, arch: &str) -> Result<&'static str> {
    Ok(match (platform, arch) {
        ("iphoneos", "arm64") => "aarch64-apple-ios",
        ("iphonesimulator", "arm64") => "aarch64-apple-ios-sim",
        ("iphonesimulator", "x86_64") => "x86_64-apple-ios",
        ("macosx", "arm64") => "aarch64-apple-darwin",
        ("macosx", "x86_64") => "x86_64-apple-darwin",
        _ => bail!("Unsupported Apple platform `{platform}` and architecture `{arch}`"),
    })
}

/// Builds the iOS target with Xcode.
pub fn ios_build(options: IosBuildOptions) -> Result<()> {
    ensure!(
        cfg!(target_os = "macos"),
        "iOS builds require macOS and Xcode"
    );
    let app = Application::new(options.package.as_deref(), options.bin.as_deref())?;
    sync_project(&app)?;
    let directory = project_dir(&app)?;
    let configuration = if options.release { "Release" } else { "Debug" };
    let derived = app.target_dir.join("xcode");
    let scheme = format!("{}-iOS", app.binary);
    let host_arch = if env::consts::ARCH == "aarch64" {
        "arm64"
    } else {
        "x86_64"
    };
    let (triple, sdk) = if options.device {
        ("aarch64-apple-ios", "iphoneos")
    } else {
        (triple("iphonesimulator", host_arch)?, "iphonesimulator")
    };
    let output = app.output_dir().join("ios").join(triple);
    fs::create_dir_all(&output)?;
    let mut xcodebuild = Command::new("xcodebuild");
    xcodebuild
        .arg("-project")
        .arg(directory.join(format!("{}.xcodeproj", app.binary)))
        .args(["-scheme", &scheme, "-configuration", configuration])
        .arg("-derivedDataPath")
        .arg(&derived);
    if let Some(path) = &options.profiling_output {
        xcodebuild.env("TESSERA_PROFILING_OUTPUT", path);
    }
    if options.device {
        let archive = output.join(format!("{}.xcarchive", app.binary));
        run(xcodebuild
            .args(["-destination", "generic/platform=iOS", "archive"])
            .arg("-archivePath")
            .arg(&archive))?;
        run(Command::new("xcodebuild")
            .arg("-exportArchive")
            .arg("-archivePath")
            .arg(&archive)
            .arg("-exportOptionsPlist")
            .arg(directory.join("ExportOptions.plist"))
            .arg("-exportPath")
            .arg(&output))?;
        output::status("Finished", output.display().to_string());
        return Ok(());
    }
    run(xcodebuild.args([
        "-sdk",
        sdk,
        "-destination",
        "generic/platform=iOS Simulator",
        &format!("ARCHS={host_arch}"),
        "ONLY_ACTIVE_ARCH=NO",
        "build",
    ]))?;
    let product = derived
        .join("Build/Products")
        .join(format!("{configuration}-{sdk}"))
        .join(format!("{}.app", app.binary));
    let bundle = output.join(format!("{}.app", app.binary));
    if bundle.exists() {
        fs::remove_dir_all(&bundle)?;
    }
    copy_bundle(&product, &bundle)?;
    output::status("Finished", bundle.display().to_string());
    Ok(())
}

fn copy_bundle(source: &Path, target: &Path) -> Result<()> {
    run(Command::new("ditto").arg(source).arg(target))
}
